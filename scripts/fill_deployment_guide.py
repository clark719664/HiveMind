"""Fill the measured-table block of docs/community/GWAYA_T4_DEPLOYMENT.md from artifacts/experiments/E16_gwaya_lite_t4_report.json.

Every number is read from the report (receipt shown in the block); nothing is typed by hand. Idempotent: rewrites only the text between the
E16-MEASURED-TABLE-BEGIN / -END markers.

    python3 scripts/fill_deployment_guide.py
"""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "artifacts" / "experiments" / "E16_gwaya_lite_t4_report.json"
GUIDE = ROOT / "docs" / "community" / "GWAYA_T4_DEPLOYMENT.md"
BEGIN, END = "<!-- E16-MEASURED-TABLE-BEGIN", "<!-- E16-MEASURED-TABLE-END -->"


def probes_of(r: dict) -> list:
    p = r["probes"]
    return p if isinstance(p, list) else p.get("probes", [])


def build(r: dict) -> str:
    tiers = r["analysis"]["tiers"]
    offload = r["controls"]["gpu_offload"]["per_probe"]
    lines = [f"{BEGIN} (generated by scripts/fill_deployment_guide.py from E16_gwaya_lite_t4_report.json, receipt {r['receipt_sha256'][:16]}; do not edit by hand) -->",
             f"Measured on a Tesla T4 with Ollama {r.get('environment', {}).get('ollama_version', '0.34.1')}, Q4_K_M, MBPP-sanitized n = 257; `run_valid` = {r['run_valid']}. "
             "VRAM = `nvidia-smi` memory.used delta over the idle baseline (CUDA context included).", "",
             "| Tier | num_ctx | VRAM (MiB) | PR estimate | ratio | decode tok/s | prompt-eval tok/s | on GPU | pass@1 raw R | pass@1 loop L | L-R, gained/lost (McNemar p) | precision of VERIFIED |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for p in probes_of(r):
        t, ctx = p["tier"], p["ctx"]
        a = tiers.get(t, {})
        if ctx == 4096:
            R, L, pr = a.get("R4096", {}), a.get("L4096", {}), a.get("paired_L_minus_R", {})
            cells = [f"{100 * R['pass_at_1']:.1f}%", f"{100 * L['pass_at_1']:.1f}%",
                     f"{100 * pr['diff']:+.1f} pts, {pr['b_only']}/{pr['a_only']} (p = {pr['mcnemar_p']:.1e})", f"{100 * a['p2_gate_calibration']['precision']:.1f}%"]
        else:
            R8 = a.get("R8192")
            cells = [f"{100 * R8['pass_at_1']:.1f}% (raw only)" if R8 else "-", "-", "-", "-"]
        ratio = p.get("ratio_measured_over_estimate")
        gp = offload.get(p["key"], {}).get("gpu_pct")
        lines.append(f"| {t.upper()} | {ctx} | {p['measured_mib']} | {p['estimator_mib']} | {ratio:.2f} | {p.get('decode_tps_median', float('nan')):.1f} | "
                     f"{p.get('prompt_eval_tps_median', float('nan')):.0f} | {'100%' if gp == 100.0 else gp} | " + " | ".join(cells) + " |")
    h = r["hypotheses"]
    lad = r["escalation_ladder"]
    lines += ["", "Registered statuses (E16 pre-registration): "
              f"H16a (7B within 6656 MiB) 4k **{h['H16a']['4096']['status']}**, 8k **{h['H16a']['8192']['status']}**; H16b (estimator within 0.80-1.25) **{h['H16b']['status']}**; "
              f"H16c (loop does not lower pass@1) {h['H16c']}; H16d (loop >= +5.0 points, p < 0.05) {h['H16d']}; H16e (precision of VERIFIED >= 0.80) {h['H16e']}; "
              f"H16f (7B decode >= 20 tok/s) **{h['H16f_descriptive']['status']}** ({h['H16f_descriptive']['decode_tps_median']:.1f} tok/s).", "",
              f"Escalation ladder (descriptive): 1.5B loop -> 3B loop -> 7B loop reaches {100 * lad['ladder_pass_at_1']:.1f}% against {100 * lad['seven_b_only_pass_at_1']:.1f}% for the 7B loop alone "
              f"(paired p = {lad['paired_ladder_vs_7b_only']['mcnemar_p']:.2f}), escalating {100 * lad['escalation_rate_3b']:.0f}% of the problems to the 3B and {100 * lad['escalation_rate_7b']:.0f}% to the 7B, "
              f"using {100 * lad['ladder_over_7b_only_time']:.0f}% of the 7B-only model time.",
              "Caveats: the gate is the vendored GWAYA zero-stub auditor plus a namespace sandbox, not GWAYA's Bubblewrap oracle; VERIFIED means audit clean and the visible test passed, "
              "and 5-7% of those solutions still fail the hidden tests; one runtime (Ollama), one seed set, one benchmark.", END]
    return "\n".join(lines)


def main() -> int:
    r = json.loads(REPORT.read_text(encoding="utf-8"))
    txt = GUIDE.read_text(encoding="utf-8")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: build(r), txt, count=1, flags=re.S)
    if new == txt:
        print("guide unchanged")
        return 0
    GUIDE.write_text(new, encoding="utf-8")
    print("guide updated from receipt", r["receipt_sha256"][:16])
    return 0


if __name__ == "__main__":
    sys.exit(main())
